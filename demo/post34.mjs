const ring = (t, amp) => {
  let x = 0;
  for (const b of RING_BEATS) {
    const tau = t - b;
    if (tau < 0) break;
    if (tau > 0.6) continue;
    x += amp(b) * SHAKE.norm * Math.sin(2 * Math.PI * SHAKE.hz * tau) * Math.exp(-tau / SHAKE.decay);
  }
  return +x.toFixed(3);
};
