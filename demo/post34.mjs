/* ---------- the beats ----------
   one per squeak. a 5ms rms envelope in dB; an onset is a climb of RISE dB
   over the LOOK seconds before it, above FLOOR, at least GAP after the last
   one; the beat is placed at the first bin of that climb. */
const ONSET = { bin: 0.005, rise: 10, look: 0.04, gap: 0.12, floor: -40 };
function detectBeats(pcm) {
  const H = Math.round(ONSET.bin * SR), n = Math.floor(pcm.length / H);
  const env = new Float32Array(n);
  for (let k = 0; k < n; k++) { let s = 0; for (let j = k * H; j < (k + 1) * H; j++) s += pcm[j] * pcm[j]; env[k] = 20 * Math.log10(Math.sqrt(s / H) + 1e-9); }
  const L = Math.round(ONSET.look / ONSET.bin), G = Math.round(ONSET.gap / ONSET.bin);
  const out = []; let last = -1e9;
  for (let k = L; k < n; k++) {
    let lo = Infinity; for (let j = k - L; j < k; j++) lo = Math.min(lo, env[j]);
    if (env[k] - lo >= ONSET.rise && env[k] > ONSET.floor && k - last >= G) {
      let s = k; while (s > 0 && env[s - 1] < env[s] && env[s] - env[s - 1] > 0.5) s--;
      out.push({ t: +(s * ONSET.bin).toFixed(3), db: +env[k].toFixed(1) });
      last = k;
    }
  }
  return out;
}
