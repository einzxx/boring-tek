function flickerAt(t) {
  let dip = 0;
  for (const k of TAPS) {
    const tau = t - k.t;
    if (tau < 0) break;
    if (tau >= TAP.down + TAP.up) continue;
    const p = tau < TAP.down ? EASE(tau / TAP.down) : 1 - GLIDE((tau - TAP.down) / TAP.up);
    dip = Math.max(dip, p);
  }
  return +(1 - SGLOW.dip * dip).toFixed(4);
}

